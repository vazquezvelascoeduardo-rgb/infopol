type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
};

const LocaleContext = createContext<Ctx | null>(null);

// La web és en CATALÀ. El selector ES/CA s'ha eliminat — l'usuari va
// decidir que el producte és monolingüe. Mantenim el dict 'es' per
// compatibilitat però mai s'usa.
function getInitialLocale(): Locale {
  return 'ca';
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => getInitialLocale());

  useEffect(() => {
    document.documentElement.lang = 'ca';
    // Esborrem qualsevol preferència vella d'ES guardada al localStorage.
    try { window.localStorage.removeItem(STORAGE_KEY); } catch {}
  }, [locale]);

  function setLocale(_l: Locale) {
    // No-op: la web és sempre en català.
    setLocaleState('ca');
  }

  function t(key: string): string {
    return DICT[key] ?? key;
  }

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useT(): Ctx {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error('useT ha d’usar-se dins de <LocaleProvider>.');
  return ctx;
}

// Helper per a plurals simples (1 → one, altres → other).
export function plural(t: Ctx['t'], count: number, keyBase: string): string {
  return t(`${keyBase}.${count === 1 ? 'one' : 'other'}`);
}
