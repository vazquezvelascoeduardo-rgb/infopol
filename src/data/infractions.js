export function searchInfractions(query = '', filter = 'totes') {
  const q = query.toLowerCase().trim();
  return INFRACTIONS.filter(inf => {
    const matchFilter =
      filter === 'totes' ||
      (filter === 'mg' && inf.sev === 'mg') ||
      (filter === 'g' && inf.sev === 'g') ||
      (filter === 'l' && inf.sev === 'l') ||
      (filter === 'lsv' && inf.article.includes('LSV')) ||
      (filter === 'rgc' && inf.article.includes('RGC'));
    if (!matchFilter) return false;
    if (!q) return true;
    return (
      inf.title.toLowerCase().includes(q) ||
      inf.article.toLowerCase().includes(q) ||
      inf.code.toLowerCase().includes(q) ||
      (inf.keywords || []).some(k => k.includes(q))
    );
  });
}
